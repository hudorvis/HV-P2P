#!/usr/bin/env python3
"""Pack the existing PDM web pages into the Olimex application image."""
import argparse
import gzip
import io
from pathlib import Path

ASSETS = {
    "index.html": "index",
    "index_ios.html": "indexIos",
    "pdm.js": "dashboard",
    "chart.umd.min.js": "chart",
    "Chart.js-LICENSE.txt": "chartLicense",
}


def pack(directory: Path) -> str:
    output = ["// Generated by tools/embed_pdm_web.py.", "#pragma once", "#include <Arduino.h>", "namespace PdmWeb {"]
    for name, symbol in ASSETS.items():
        stream = io.BytesIO()
        with gzip.GzipFile(filename="", fileobj=stream, mode="wb", mtime=0) as compressed:
            compressed.write((directory / "web" / name).read_bytes())
        data = stream.getvalue()
        output.append(f"const uint8_t {symbol}[] PROGMEM = {{")
        for start in range(0, len(data), 16):
            output.append("  " + ", ".join(f"0x{byte:02x}" for byte in data[start:start+16]) + ",")
        output.append("};")
    return "\n".join([*output, "}  // namespace PdmWeb", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("sketch", type=Path)
    args = parser.parse_args()
    (args.sketch / "pdm_web_assets.h").write_text(pack(args.sketch), encoding="ascii")
